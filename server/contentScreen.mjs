/* 词表**编译一次**（正则没有 g 标志，test 不带状态，可安全复用） */
const COMPILED = CATEGORIES.map(category => ({
  id: category.id,
  label: category.label,
  patterns: category.patterns.map(pattern => new RegExp(pattern.source)),
}));

/**
 * 检查一段文本（通常是用户提示词 / 负向提示词 / 工作台各字段拼起来的净文本）。
 * @param {string} text
 * @returns {{ ok: boolean, hits: Array<{id:string,label:string}>, reason: string }}
 */
export function screenPromptText(text) {
  const value = typeof text === 'string' ? text : String(text ?? '');
  if (!value.trim()) return { ok: true, hits: [], reason: '' };
  /* 归一化：去掉零宽字符与全角空格 —— 夹字/零宽是最常见的绕过手法 */
  const normalized = value.replace(/[\u200B-\u200D\uFEFF]/g, '').replace(/\u3000/g, ' ');
  const hits = [];
  for (const category of COMPILED) {
    if (category.patterns.some(pattern => pattern.test(normalized))) {
      hits.push({ id: category.id, label: category.label });
    }
  }
  return {
    ok: hits.length === 0,
    hits,
    reason: hits.length ? `提示词包含不允许的内容（${hits.map(item => item.label).join('、')}）` : '',
  };
}

/* 诊断/自证用：把类别清单暴露出来（测试与运维要能核对"到底拦了哪几类"） */
export function contentScreenCategories() {
  return COMPILED.map(category => ({ id: category.id, label: category.label, patternCount: category.patterns.length }));
}
